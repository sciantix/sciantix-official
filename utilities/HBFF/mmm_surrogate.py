# Analysis of each run

def run_id(folder):
    """Id of a run folder run_<id> (the rows of mmm_inputs/index.txt)."""
    return os.path.basename(os.path.normpath(folder)).removeprefix("run_")


def analyse(folder, index):
    run = run_id(folder)
    if run not in index:
        raise SystemExit(f"run {run} (folder {folder}) is not in {INDEX}")
    factors = index[run]
    p = read_pores(folder)
    load = load_of(p)
    fits = class_fits(p)

    # the classes of the run: what --fit takes from pores.csv (u, share, pores, mu, sig, ln_p_rel)
    R_V = factors["R_V_um"]
    side = np.unique(p["side_um"])
    lines = [f"# s_hat per pore class of run {run} (mmm_surrogate.py): ln s_hat ~ normal(mu, sig) in every class",
             f"# run: xi = {factors['xi']:g}, s = {factors['s']:g}, R_V = {R_V:g} um (mmm_inputs/index.txt); "
             f"{len(np.unique(p['cube']))} cubes of {', '.join(f'{v:g}' for v in side)} um, {len(p['s_hat'])} pores, "
             f"porosity of the cubes {np.mean(p['xi']):.4f}",
             ("# MMM at unit pressure in every pore, s_hat = (sigma + h) / (1 - h): zero macroscopic stress (D5.2)"
              if load == "unit" else
              "# MMM with the pressure p_k of its class in every pore (pk cubes), s_hat on the own pressure of the pore, "
              f"at zero macroscopic stress (plot_bubbles.py); eta_bar = {factors['eta_bar']:g}"),
             f"# u = ln(R / R_V); share = share of the pore volume of the cubes; pairs with sigma_R = "
             f"{SIGMA_R_MMM / 1e6:g} MPa of D5.2 (on NFIR: calibration_nfir.txt); ln_p_rel = ln(p_k / p_ref), p_ref = volume mean of the pressures",
             f"# {'R_um':>10s}{'u':>10s}{'share':>10s}{'pores':>8s}{'mu':>10s}{'sig':>10s}{'mean':>9s}{'q05':>8s}"
             f"{'q50':>8s}{'q95':>8s}{'ln_p_rel':>10s}"]
    for f in fits:
        q05, q50, q95 = np.quantile(f["s"], (0.05, 0.5, 0.95))
        lines.append(f"  {f['R']:10.6f}{np.log(f['R'] / R_V):10.5f}{f['share']:10.6f}{f['pores']:8d}{f['mu']:10.6f}"
                     f"{f['sig']:10.6f}{np.mean(f['s']):9.4f}{q05:8.4f}{q50:8.4f}{q95:8.4f}{f['rho']:10.5f}")
    print("\n".join(lines))

    # closure: FGR of the cubes against the log-normal classes
    xc_all = p["x_c"][np.isfinite(p["x_c"])]
    x = np.linspace(min(0.3, 0.8 * np.quantile(xc_all, 0.001)), max(1.6, 1.25 * np.quantile(xc_all, 0.999)), 2601)
    cubes = fgr_cubes(p, x)
    mean, model = cubes.mean(axis=0), fgr_model(fits, x)
    gap = np.abs(model - mean)
    print(f"\n== closure: FGR of the {len(cubes)} cubes against the log-normal classes ==")
    print(f"largest difference {100 * gap.max():.2f} percentage points of FGR, at x = p / sigma_R = {x[np.argmax(gap)]:.3f}")
    print(f"{'FGR_%':>6s}{'x_cubes':>9s}{'x_model':>9s}{'diff_%':>8s}")
    for lv in LEVELS:
        xc, xm = level_x(x, mean, lv), level_x(x, model, lv)
        print(f"{100 * lv:6.0f}{xc:9.4f}{xm:9.4f}{100 * (xm / xc - 1):8.2f}")

    # cubes per run
    sizes = [m for m in (1, 2, 3, 5, 10) if m <= len(cubes)]
    boot = bootstrap(p, x, sizes)
    central = np.array([f["share"] >= 0.05 for f in fits])
    print(f"\n== cubes per run: error (2 standard deviations, bootstrap of {BOOT} draws) with m cubes ==")
    print("mu, sig: largest over the classes with >= 5 % of the pore volume / over all the classes (absolute, on ln s_hat); "
          "x: relative error of the critical p / sigma_R at the level of FGR")
    print(f"{'m':>3s}{'mu_main':>9s}{'mu_all':>8s}{'sig_main':>9s}{'sig_all':>8s}" + "".join(f"{f'x{100 * lv:.0f}%':>8s}" for lv in LEVELS))
    for m in sizes:
        b = boot[m]
        print(f"{m:3d}{b['mu'][central].max():9.4f}{b['mu'].max():8.4f}{b['sig'][central].max():9.4f}{b['sig'].max():8.4f}"
              + "".join(f"{100 * v:7.2f}%" for v in b["x"]))

    # MMM against the mean-field step of J19, same pressure in every class, P_h = 0, no surface tension
    xi = float(np.mean(p["xi"]))
    p_j19 = SIGMA_R_J19 * (1.0 - xi) / xi
    print(f"\n== MMM against J19 ({'same pressure in every class' if load == 'unit' else 'p = p_ref, the volume mean of the class pressures'}, P_h = 0, no 2 gamma / R) ==")
    print(f"J19: every class breaks at p = sigma_R (1 - xi) / xi = {p_j19 / 1e6:.1f} MPa (sigma_R = {SIGMA_R_J19 / 1e6:g} MPa)")
    print("MMM (sigma_R = 275 MPa): " + ", ".join(f"FGR {100 * lv:.0f} % at {level_x(x, model, lv) * SIGMA_R_MMM / 1e6:.0f} MPa"
                                                  for lv in LEVELS))
    figure(run, fits, factors, x, cubes, model, boot, sizes, p_j19, central, load)

