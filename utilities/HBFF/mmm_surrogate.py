# Training and validation of the surrogate in 5 steps
def fit(load, c, index):
    design = np.array([r != "NFIR" for r in c["run"]])  # the runs of the hypercube; NFIR is the reference, kept as a test
    runs = sorted(set(c["run"][design]))
    if len(runs) < 5:
        print(f"{load}: {len(runs)} runs of the hypercube, too few for a surrogate")
        return 1
    names = FIT_INPUTS[load]
    rms = lambda a: float(np.sqrt(np.mean(np.square(a))))

    # %% 1. leave one run out: the surrogate and two baselines ---------------------------------------------------------
    # Every run is predicted by the models fitted on the other runs, against its own table. The table of a run of one
    # cube is itself noisy: the pores of its classes give var(mu_k) = sig_k^2 / n_k, var(ln sig_k) = 1 / (2 (n_k - 1)),
    # and this noise of x is the floor (on run NFIR it is 0.7-0.9 %, the scatter between its 10 cubes 0.6-1.0 %).
    models = {"surrogate": {}, "trend only": {"trend_only": True}, "no state (u only)": {"names": ("u",)}}
    res = {m: [] for m in models}
    noise, spread, pairs = [], [], {"mu": [], "sig": []}
    for run in runs:
        rows = c["run"] == run
        test = {k: v[rows] for k, v in c.items()}
        var_mu, var_lnsig = np.diag(test["sig"] ** 2 / test["pores"]), np.diag(1.0 / (2.0 * (test["pores"] - 1.0)))
        noise.append(x_spread(test["share"], test["rho"], test["mu"], var_mu, np.log(test["sig"]), var_lnsig))
        for m, options in models.items():
            model = surrogate(c, load, design & ~rows, **options)
            if m == "surrogate":
                # the spread the surrogate predicts for the table: its own (Gaussian process) plus the noise of the table
                (mu, C_mu), (lnsig, C_lnsig) = model(test, cov=True)
                spread.append(x_spread(test["share"], test["rho"], mu, C_mu + var_mu, lnsig, C_lnsig + var_lnsig))
                sig = np.exp(lnsig)
                pairs["mu"].append((test["mu"], mu, test["share"]))
                pairs["sig"].append((test["sig"], sig, test["share"]))
            else:
                mu, sig = model(test)
            res[m].append(compare(c, rows, mu, sig))
    err = {m: np.array([r[4] for r in res[m]]) for m in models}   # (runs, levels)
    dfgr = {m: np.array([r[5] for r in res[m]]) for m in models}  # (runs)
    noise, spread = np.array(noise), np.array(spread)
    z = err["surrogate"] / spread

    lines = [f"# Surrogate of s_hat, load {load} (python3 mmm_surrogate.py --fit {load}): mu and ln sig of ln s_hat per class "
             f"against ({', '.join(names)}), linear trend + Gaussian process",
             f"# {len(runs)} runs of the hypercube, {int(design.sum())} classes with at least 3 pores",
             "#",
             "# == 1. Leave one run out: every run predicted by the surrogate fitted on the others, against its own table ==",
             f"# - d_mu, d_lnsig: largest difference over the classes with >= {100 * MAIN_SHARE:g} % of the pore volume (main) "
             "and over all the classes",
             "# - x_<level>: error (%) of x = p_ref / sigma_R at that level of FGR, rebuilt with the shares of the run",
             "# - dFGR: largest difference of the FGR curve over x (points of FGR)",
             "# - noise: rms over the levels of the noise of x of the table (pores of its classes, %); std: the spread of x "
             "the surrogate predicts for the table (its Gaussian process + the noise of the table, %)",
             f"# {'run':>5s}{'xi':>8s}{'s':>8s}{'eta_bar':>9s}{'d_mu_main':>11s}{'d_mu_all':>10s}{'d_lnsig_main':>14s}"
             f"{'d_lnsig_all':>13s}" + "".join(f"{f'x_{100 * lv:.0f}%':>8s}" for lv in LEVELS)
             + f"{'dFGR':>7s}{'noise':>7s}{'std':>7s}"]
    for k, run in enumerate(runs):
        f, r = index[run], res["surrogate"][k]
        lines.append(f"  {run:>5s}{f['xi']:8.4f}{f['s']:8.4f}{f['eta_bar']:9.4f}{r[0]:11.4f}{r[1]:10.4f}{r[2]:14.4f}{r[3]:13.4f}"
                     + "".join(f"{100 * v:8.2f}" for v in r[4])
                     + f"{100 * r[5]:7.2f}{100 * rms(noise[k]):7.2f}{100 * rms(spread[k]):7.2f}")
    stats = np.array([r[:4] for r in res["surrogate"]])
    e = err["surrogate"]
    lines.append(f"# {'rms':>5s}{'':25s}" + "".join(f"{rms(stats[:, j]):{w}.4f}" for j, w in enumerate((11, 10, 14, 13)))
                 + "".join(f"{100 * rms(e[:, j]):8.2f}" for j in range(len(LEVELS)))
                 + f"{100 * rms(dfgr['surrogate']):7.2f}{100 * rms(noise):7.2f}{100 * rms(spread):7.2f}")
    worst = np.argmax(np.abs(e), axis=0)
    lines.append(f"# {'worst':>5s}{'':73s}" + "".join(f"{100 * e[w, j]:8.2f}" for j, w in enumerate(worst))
                 + f"{100 * dfgr['surrogate'].max():7.2f}")
    lines.append(f"# {'run':>5s}{'':73s}" + "".join(f"{runs[w]:>8s}" for w in worst)
                 + f"{runs[int(np.argmax(dfgr['surrogate']))]:>7s}")

    # %% 2. performance: the surrogate against the baselines, the noise, and the spread it predicts --------------------
    floor = rms(noise)
    lines += ["#", f"# == 2. Performance over the {len(runs)} runs and the {len(LEVELS)} levels of FGR (leave one run out) ==",
              "# x: error of x = p_ref / sigma_R at the levels (%), rms and worst; dFGR: largest difference of the FGR curve "
              "over x, rms over the runs and worst (points)",
              "# trend only: the linear trend in the same inputs, no Gaussian process; no state: mu and sig against u only, "
              "i.e. one table for every state of the pores",
              f"# {'model':<30s}{'rms_x_%':>9s}{'worst_x_%':>11s}{'rms_dFGR':>10s}{'worst_dFGR':>12s}"]
    for m in models:
        lines.append(f"  {m:<30s}{100 * rms(err[m]):9.2f}{100 * err[m].flat[np.argmax(np.abs(err[m]))]:11.2f}"
                     f"{100 * rms(dfgr[m]):10.2f}{100 * dfgr[m].max():12.2f}")
    lines.append(f"  {'noise of the tables':<30s}{100 * floor:9.2f}{100 * noise.max():11.2f}")
    excess = np.sqrt(max(rms(e) ** 2 - floor**2, 0.0))
    skill = 1.0 - rms(e) ** 2 / rms(err["no state (u only)"]) ** 2
    lines += [f"# error of the surrogate above the noise of the tables, sqrt(rms^2 - noise^2): {100 * excess:.2f} %",
              f"# skill against no state, 1 - mse / mse_no_state: {skill:.3f} (1: exact, 0: no better than one table for "
              "every state)",
              f"# spread predicted against the error: |error| < 2 std for {100 * np.mean(np.abs(z) < 2):.0f} % of the "
              f"(run, level) pairs (95 % if the spread is right), rms of error / std = {rms(z):.2f} (1 if right)"]

    # %% 3. learning curve: fitted on m runs drawn at random, the other runs predicted ---------------------------------
    rng = np.random.default_rng(LEARN_SEED)
    learn = {}
    for m in [k for k in LEARN_SIZES if k < len(runs) - 1]:
        learn[m] = []
        for _ in range(LEARN_REPEATS):
            train = rng.choice(runs, m, replace=False)
            model = surrogate(c, load, np.isin(c["run"], train))
            out = [compare(c, c["run"] == run, *model({k: v[c["run"] == run] for k, v in c.items()}))
                   for run in runs if run not in train]
            learn[m].append((rms([o[4] for o in out]), rms([o[5] for o in out])))
    learn[len(runs) - 1] = [(rms(e), rms(dfgr["surrogate"]))]
    lines += ["#", f"# == 3. Learning curve: fitted on m runs drawn at random ({LEARN_REPEATS} draws; m = {len(runs) - 1}: "
                   "leave one run out), the other runs predicted ==",
              f"# {'m':>3s}{'draws':>7s}{'rms_x_%':>9s}{'min_x_%':>9s}{'max_x_%':>9s}{'rms_dFGR':>10s}"]
    for m, v in learn.items():
        v = 100 * np.array(v)
        lines.append(f"  {m:3d}{len(v):7d}{rms(v[:, 0]):9.2f}{v[:, 0].min():9.2f}{v[:, 0].max():9.2f}{rms(v[:, 1]):10.2f}")

    # %% 4. run NFIR (not in the hypercube), predicted by the surrogate of all the runs ------------------------------
    full = surrogate(c, load, design)
    test = c["run"] == "NFIR"
    if test.any():
        mu, sig = full({k: v[test] for k, v in c.items()})
        r = compare(c, test, mu, sig)
        f = index["NFIR"]
        lines += ["#", "# == 4. Run NFIR (not in the hypercube) predicted by the surrogate of all the runs, against its own table ==",
                  f"  {'NFIR':>5s}{f['xi']:8.4f}{f['s']:8.4f}{f['eta_bar']:9.4f}{r[0]:11.4f}{r[1]:10.4f}{r[2]:14.4f}{r[3]:13.4f}"
                  + "".join(f"{100 * v:8.2f}" for v in r[4]) + f"{100 * r[5]:7.2f}",
                  f"# {'u':>9s}{'share':>9s}{'mu':>9s}{'mu_fit':>9s}{'sig':>9s}{'sig_fit':>9s}"]
        lines += [f"  {u:9.4f}{sh:9.4f}{a:9.4f}{b:9.4f}{d:9.4f}{g:9.4f}"
                  for u, sh, a, b, d, g in zip(c["u"][test], c["share"][test], c["mu"][test], mu, c["sig"][test], sig)]

    # %% 5. what the surrogate of all the runs does with every input ----------------------------------------------------
    lines += ["#", "# == 5. Inputs of the surrogate of all the runs ==",
              "# trend: change of mu (or ln sig) per standard deviation of the input over the runs; length: correlation "
              "length of the Gaussian process in standard deviations of the input (0.3 and 30 are the bounds: 30 = no "
              "structure beyond the trend); amplitude, white: standard deviations of the Gaussian process and of the "
              "scatter between runs that the inputs do not explain",
              f"# {'':14s}" + "".join(f"{k:>9s}" for k in names) + f"{'amplitude':>11s}{'white':>9s}"]
    for key in ("mu", "lnsig"):
        a = full.about[key]
        lines.append(f"  {key + ' trend':<14s}" + "".join(f"{v:9.4f}" for v in a["trend"]))
        lines.append(f"  {key + ' length':<14s}" + "".join(f"{v:9.2f}" for v in a["length"])
                     + f"{a['amplitude']:11.4f}{a['white']:9.4f}")
    os.makedirs(OUT_DIR, exist_ok=True)
    path = os.path.join(OUT_DIR, f"surrogate_{load}.txt")
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\n".join(lines))

    # %% 6. the surrogate of all the runs for SCIANTIX ------------------------------------------------------------------
    # input_hbs_shat.txt of a case of option 4 (HighBurnupStructureFragmentation.C reads it): the inputs are clipped
    # to the range of the runs, standardised, and mu, ln sig = trend + Gaussian process. The file ends with test points
    # that SCIANTIX evaluates when it reads the file (it stops if it does not find the same mu and sig).
    ex = full.export
    X = np.column_stack([c[k][design] for k in names])
    f9 = lambda v: " ".join(f"{float(a):.17g}" for a in np.atleast_1d(v))
    out = [f"# s_hat of MMM for option 4 of SCIANTIX (python3 mmm_surrogate.py --fit {load}, {len(runs)} runs of the "
           "hypercube): copy it as input_hbs_shat.txt into the folder of a case with iHighBurnupStructureFragmentation = 4",
           "# ln s_hat of the pores of a class ~ normal(mu, sig); mu and ln sig = f(z) with z_d = (x_d - mean_d) / std_d, the "
           "inputs x_d clipped to [lower_d, upper_d] (the range of the runs),",
           "#   f(z) = beta_0 + sum_d beta_d z_d + scale * amplitude2 * sum_j alpha_j exp(-0.5 sum_d ((z_d - z_jd) / length_d)^2)",
           "# sigma_R (Pa) pairs with this s_hat: 275 MPa of D5.2 here; calibrate_sigma_r.py writes the value calibrated on NFIR "
           "into the regression cases",
           f"sigma_R {SIGMA_R_MMM:.17g}",
           f"inputs {len(names)} {' '.join(names)}",
           f"mean {f9(ex['mu']['mean'])}", f"std {f9(ex['mu']['std'])}",
           f"lower {f9(X.min(axis=0))}", f"upper {f9(X.max(axis=0))}"]
    for key in ("mu", "lnsig"):
        e_ = ex[key]
        assert np.allclose(e_["mean"], ex["mu"]["mean"]) and np.allclose(e_["std"], ex["mu"]["std"])
        out += [f"output {key}", f"beta {f9(e_['beta'])}", f"scale {f9(e_['scale'])}",
                f"amplitude2 {f9(e_['amplitude2'])}", f"length {f9(e_['length'])}", f"points {len(e_['alpha'])}"]
        out += [f"{f9(z)} {f9(a)}" for z, a in zip(e_["points"], e_["alpha"])]
    # test points: every 10th class of the runs and the classes of run NFIR, without clipping
    pick = np.nonzero(design)[0][::10].tolist() + np.nonzero(c["run"] == "NFIR")[0].tolist()
    rows = {k: v[pick] for k, v in c.items()}
    mu, sig = full(rows)
    # the same with the formula of the file, as SCIANTIX evaluates it
    def formula(e_, x):
        z = (x - e_["mean"]) / e_["std"]
        d2 = (((z[:, None, :] - e_["points"][None, :, :]) / e_["length"]) ** 2).sum(axis=2)
        return np.c_[np.ones(len(z)), z] @ e_["beta"] + e_["scale"] * e_["amplitude2"] * np.exp(-0.5 * d2) @ e_["alpha"]
    x_test = np.column_stack([rows[k] for k in names])
    gap = max(np.abs(formula(ex["mu"], x_test) - mu).max(), np.abs(np.exp(formula(ex["lnsig"], x_test)) / sig - 1.0).max())
    assert gap < 1e-10, f"the formula of the file misses the surrogate by {gap:.1e}"
    out.append(f"tests {len(pick)}")
    out += [f"{f9(x)} {f9(m)} {f9(g)}" for x, m, g in zip(x_test, mu, sig)]
    with open(os.path.join(OUT_DIR, f"surrogate_{load}_sciantix.txt"), "w") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"wrote mmm_outputs/surrogate_{load}_sciantix.txt (the formula of the file reproduces the surrogate to {gap:.1e})")

    # %% figure ---------------------------------------------------------------------------------------------------------
    fig, ax = plt.subplots(2, 3, figsize=(17.0, 10.0))
    for a, key, label in ((ax[0, 0], "mu", r"$\mu_k$ (mean of ln $\hat s$)"), (ax[0, 1], "sig", r"$\sigma_k$ (std of ln $\hat s$)")):
        for table, fitted, share in pairs[key]:
            main = share >= MAIN_SHARE
            a.plot(table[~main], fitted[~main], "o", color=GREY, ms=3.5, alpha=0.7)
            a.plot(table[main], fitted[main], "o", color=BLUE, ms=4.5, alpha=0.8)
        lo, hi = a.get_xlim()
        a.plot([lo, hi], [lo, hi], color="black", lw=0.8)
        a.plot([], [], "o", color=BLUE, label=rf"classes with $\geq$ {100 * MAIN_SHARE:g} % of the pore volume")
        a.plot([], [], "o", color=GREY, label="other classes")
        a.set(xlabel=f"{label}, table of the run", ylabel="predicted by the other runs", title=f"{label}: leave one run out")
        a.legend(frameon=False, fontsize=8)
    a = ax[0, 2]
    xi = np.array([index[r]["xi"] for r in runs])
    shown = [LEVELS.index(lv) for lv in (0.05, 0.50, 0.90)]
    for j, color, marker in zip(shown, (ORANGE, BLUE, GREEN), ("s", "o", "^")):
        a.plot(xi, 100 * e[:, j], marker, color=color, ms=5, ls="none", label=f"FGR {100 * LEVELS[j]:.0f} %")
    for k, run in enumerate(runs):
        j = shown[int(np.argmax(np.abs(e[k, shown])))]
        if abs(e[k, j]) > 0.08:  # the label on the largest of the points drawn
            a.annotate(run, (xi[k], 100 * e[k, j]), fontsize=7, color=GREY, xytext=(4, 0), textcoords="offset points")
    a.axhline(0.0, color="black", lw=0.8)
    a.set(xlabel=r"porosity $\xi$ of the run", ylabel=r"error of $x = p_{ref} / \sigma_R$ at the level of FGR (%)",
          title="Load at a level of FGR: leave one run out")
    a.legend(frameon=False, fontsize=8)

    a = ax[1, 0]
    order = np.argsort(xi)
    pos = np.arange(len(runs))
    for m, color, marker in zip(models, (BLUE, ORANGE, GREY), ("o", "s", "^")):
        a.plot(pos, [100 * rms(err[m][k]) for k in order], marker, color=color, ms=6, ls="none",
               label=f"{m} (rms {100 * rms(err[m]):.1f} %)")
    a.plot(pos, [100 * rms(noise[k]) for k in order], "_", color="black", ms=12, mew=2, ls="none",
           label=f"noise of the table (rms {100 * floor:.1f} %)")
    a.set_xticks(pos, [runs[k] for k in order], rotation=90, fontsize=7)
    a.set(xlabel=r"run, by increasing $\xi$", ylabel="error of x, rms over the levels of FGR (%)", ylim=(0, None),
          title="Leave one run out: surrogate against the baselines")
    a.legend(frameon=False, fontsize=8)

    a = ax[1, 1]
    sizes = sorted(learn)
    for m in sizes:
        v = 100 * np.array(learn[m])[:, 0]
        a.plot(np.full(len(v), m), v, "o", color=BLUE, ms=4, alpha=0.4)
    a.plot(sizes, [100 * rms(np.array(learn[m])[:, 0]) for m in sizes], "o-", color=BLUE, lw=2, ms=6,
           label="surrogate (rms over the draws; dots: one draw)")
    a.axhline(100 * floor, color="black", lw=1.2, ls="--", label="noise of the tables (one cube per run)")
    a.set(xlabel="runs fitted", ylabel="error of x on the other runs, rms (%)", ylim=(0, None), xticks=sizes,
          title="Learning curve")
    a.legend(frameon=False, fontsize=8)

    a = ax[1, 2]
    lim = 1.1 * 100 * max(np.abs(e).max(), spread.max())
    a.plot(100 * spread.ravel(), 100 * np.abs(e).ravel(), "o", color=BLUE, ms=4, alpha=0.6, label="one run, one level of FGR")
    a.plot([0, lim], [0, lim], color="black", lw=0.8, label="|error| = std")
    a.plot([0, lim / 2], [0, lim], color="black", lw=0.8, ls="--", label="|error| = 2 std")
    a.set(xlabel="std of x predicted (Gaussian process + noise of the table, %)", ylabel="|error| of x (%)",
          xlim=(0, lim), ylim=(0, lim),
          title=f"Spread predicted against the error ({100 * np.mean(np.abs(z) < 2):.0f} % within 2 std)")
    a.legend(frameon=False, fontsize=8)
    for a in ax.ravel():
        a.grid(True, color=GRID)
    fig.suptitle(f"Surrogate of $\\hat s$, load {load}: inputs ({', '.join(names)}), {len(runs)} runs", fontsize=11)
    fig.tight_layout()
    fig.savefig(os.path.join(OUT_DIR, f"surrogate_{load}.png"), dpi=150)
    plt.close(fig)
    print(f"wrote mmm_outputs/surrogate_{load}.txt and mmm_outputs/surrogate_{load}.png")
    return 0


