"""
Surrogate model of the pore-scale stress amplification factor s_hat for high-burnup fuel fragmentation in SCIANTIX.
@ author: E.Cappellari, POLIMI-CEA 2026
@ date:   October 2026

Input: 
    - MMM run folders (run_<id>), each containing pores.csv, generated by break_order.py.
    - Run parameters (xi, s, eta_bar, R_V) from mmm_inputs/index.txt.

Output:
    - Per-run characterization (printed) and its diagnostic plot, mmm_outputs/shat_<run>.png (shat_pk_<run>.png for pk).
    - Surrogate performance tables and validation plots.
    - Surrogate parameter files for SCIANTIX (surrogate_<load>_sciantix.txt).
    
Two load configurations:
    unit: uniform pressure across all pores; s_hat characterizes the pore geometry.
    pk:   class-dependent pressure; s_hat is evaluated at the pressure of each pore's own class.

Workflow
    1. MMM characterization
       Read pore-level results and determine the log-normal distribution of s_hat in each pore-size class.

    2. Single-run assessment
       Reconstruct the fragmentation gas release (FGR), assess the closure against pore-level results, quantify sampling uncertainty and compare with the J19 mean-field model.

    3. Surrogate development
       Fit a linear trend plus a Gaussian process to predict the mean and standard deviation of ln(s_hat) across pore-size classes.

    4. Model validation
       Assess predictive accuracy through leave-one-run-out cross-validation, comparison with baseline models, learning curves and independent validation on NFIR.

    5. SCIANTIX implementation
       Export the trained surrogate and verify the consistency of its numerical evaluation against the Python model.

usage
    python3 utilities/HBFF/mmm_surrogate.py <run folder> [<run folder> ...]     classes of the runs, and their plots
    python3 utilities/HBFF/mmm_surrogate.py --fit <folder> [<folder> ...]       surrogates over the runs
    --fit reads the pores.csv of every run folder at or below the folders given (e.g. the tree of the hypercube and
    results/<test>/run_NFIR) and fits every load with at least 5 runs of the hypercube; run NFIR, if given, is the test.
"""

