# Surrogate over the Latin hypercube

def read_classes(folders, index):
    """The classes of every run folder at or below `folders`, by load: {load: dict of arrays (run, the factors of index.txt, u, share, pores, mu, sig, rho)}, one row per class and run, the runs in the order of their id.
    Classes with fewer than 3 pores have no sig worth fitting: left out."""
    runs = sorted({os.path.dirname(os.path.abspath(path)) for folder in folders
                   for path in glob.glob(os.path.join(folder, "**", "pores.csv"), recursive=True)}, key=run_id)
    if not runs:
        raise SystemExit(f"no pores.csv at or below {', '.join(folders)}")
    classes = {}
    for folder in runs:
        run = run_id(folder)
        if run not in index:
            raise SystemExit(f"run {run} (folder {folder}) is not in {INDEX}")
        p = read_pores(folder)
        rows = classes.setdefault(load_of(p), {k: [] for k in ("run", "xi", "s", "eta_bar", "u", "share", "pores", "mu",
                                                                "sig", "rho")})
        if run in rows["run"]:
            raise SystemExit(f"run {run} twice for the load {load_of(p)}: {folder} and another folder")
        for f in class_fits(p):
            if f["pores"] < 3 or not np.isfinite(f["sig"]) or f["sig"] <= 0.0:
                continue
            rows["run"].append(run)
            for k in ("xi", "s", "eta_bar"):
                rows[k].append(index[run][k])
            rows["u"].append(np.log(f["R"] / index[run]["R_V_um"]))
            for k in ("share", "pores", "mu", "sig", "rho"):
                rows[k].append(f[k])
    return {load: {k: np.array(v) for k, v in rows.items()} for load, rows in classes.items()}


def gp_predictor(X, y, var, trend_only=False):
    """Linear trend (weighted by the known noise) plus a Gaussian process on the residual, fitted on the points X (rows) with the values y of noise variance var; trend_only: the trend alone. Returns the function (X_new, cov=False) -> prediction, or (prediction, covariance) with cov: the covariance of the Gaussian process with its white part (the scatter between runs that the inputs do not explain), the uncertainty of the trend left out.
    Its attribute `about`: trend per standard deviation of every input, length scales (in standard deviations), amplitude and white scatter of the Gaussian process (standard deviations, in the units of y)."""
    try:
        from sklearn.gaussian_process import GaussianProcessRegressor
        from sklearn.gaussian_process.kernels import RBF, ConstantKernel, WhiteKernel
    except ImportError:
        raise SystemExit("the surrogate needs scikit-learn: pip install scikit-learn")
    import warnings
    # input normalization
    mean, std = X.mean(axis=0), X.std(axis=0)
    std[std == 0.0] = 1.0
    A = (X - mean) / std
    # linear trend weighted
    D = np.c_[np.ones(len(A)), A]
    w = 1.0 / np.sqrt(var + 1e-4)
    beta = np.linalg.lstsq(D * w[:, None], y * w, rcond=None)[0]
    # gaussian process on residual
    res = y - D @ beta
    scale = res.std() or 1.0
    gp = None
    if not trend_only:
        # Constant kernel: correlation amplitude
        # RBF: correlation between points nearby in the input space - anysotropic
        # White kernel: residual scatter, scatter between runs that the inputs do not explain
        kernel = (ConstantKernel(1.0, (1e-2, 1e2)) * RBF(np.ones(A.shape[1]), (0.3, 30.0))
                  + WhiteKernel(1e-2, (1e-5, 1.0)))  
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")  # length scales at their bounds: a flat direction
            gp = GaussianProcessRegressor(kernel, alpha=var / scale**2, n_restarts_optimizer=2, random_state=0).fit(A, res / scale)

    def predict(X_new, cov=False):
        B = (np.atleast_2d(X_new) - mean) / std
        trend = np.c_[np.ones(len(B)), B] @ beta
        if gp is None:
            return (trend, np.zeros((len(B), len(B)))) if cov else trend
        if not cov:
            return trend + gp.predict(B) * scale
        m, C = gp.predict(B, return_cov=True)
        return trend + m * scale, C * scale**2
    k = gp.kernel_ if gp is not None else None
    # what SCIANTIX needs to evaluate it (section 6 of fit): the mean of the Gaussian process at z is
    # scale * amplitude2 * sum_j alpha_j exp(-0.5 sum_d ((z_d - z_jd) / length_d)^2), its white part does not enter
    predict.export = None if k is None else {"mean": mean, "std": std, "beta": beta, "scale": scale,
                                             "amplitude2": k.k1.k1.constant_value,
                                             "length": np.atleast_1d(k.k1.k2.length_scale) * np.ones(A.shape[1]),
                                             "points": gp.X_train_, "alpha": gp.alpha_}
    predict.about = {"trend": beta[1:],
                     "length": np.atleast_1d(k.k1.k2.length_scale) if k else np.full(A.shape[1], np.nan),
                     "amplitude": np.sqrt(k.k1.k1.constant_value) * scale if k else np.nan,
                     "white": np.sqrt(k.k2.noise_level) * scale if k else np.nan}
    return predict

#%%
# Surrogate for two independent models: mu and ln(sig)

def surrogate(c, load, keep=None, names=None, trend_only=False):
    """Predictors of mu and sig of the classes from the rows `keep` of the classes c, on the inputs `names`
    (FIT_INPUTS[load] if None): (classes, cov=False) -> mu, sig; with cov, (mean, covariance) of mu and of ln sig."""
    names = FIT_INPUTS[load] if names is None else names
    keep = np.ones(len(c["mu"]), dtype=bool) if keep is None else keep
    X = np.column_stack([c[k][keep] for k in names])
    mu = gp_predictor(X, c["mu"][keep], c["sig"][keep] ** 2 / c["pores"][keep], trend_only)
    lnsig = gp_predictor(X, np.log(c["sig"][keep]), 1.0 / (2.0 * (c["pores"][keep] - 1.0)), trend_only)

    def predict(rows, cov=False):
        X_new = np.column_stack([rows[k] for k in names])
        if cov:
            return mu(X_new, True), lnsig(X_new, True)
        return mu(X_new), np.exp(lnsig(X_new))
    predict.about = {"mu": mu.about, "lnsig": lnsig.about}
    predict.export = {"mu": mu.export, "lnsig": lnsig.export}
    return predict

#%%
# Functions to evaluate previsions

def fgr_curve(share, mu, sig, rho):
    """FGR on X_GRID from the classes, 1 at the end (the classes with fewer than 3 pores are left out by read_classes)."""
    fgr = fgr_model([{"share": a, "mu": b, "sig": d, "rho": e} for a, b, d, e in zip(share, mu, sig, rho)], X_GRID)
    return fgr / fgr[-1]


def compare(c, rows, mu, sig):
    """Prediction (mu, sig) against the table for the classes `rows` of one run: largest |d mu| and |d ln sig| over the
    main classes and over all, the relative error of x at the LEVELS and the largest difference of the FGR over x
    (fraction of the pore volume)."""
    main = c["share"][rows] >= MAIN_SHARE
    d_mu, d_sig = np.abs(mu - c["mu"][rows]), np.abs(np.log(sig / c["sig"][rows]))
    share, rho = c["share"][rows], c["rho"][rows]
    f_table, f_fit = fgr_curve(share, c["mu"][rows], c["sig"][rows], rho), fgr_curve(share, mu, sig, rho)
    x_table = np.array([level_x(X_GRID, f_table, lv) for lv in LEVELS])
    x_fit = np.array([level_x(X_GRID, f_fit, lv) for lv in LEVELS])
    return d_mu[main].max(), d_mu.max(), d_sig[main].max(), d_sig.max(), x_fit / x_table - 1.0, np.abs(f_fit - f_table).max()


def x_spread(share, rho, mu, C_mu, lnsig, C_lnsig):
    """Relative standard deviation of x at the LEVELS when mu and ln sig of the classes are normal with these means and
    covariances (Monte Carlo, MC_DRAWS draws)."""
    rng = np.random.default_rng(MC_SEED)
    draws = zip(rng.multivariate_normal(mu, C_mu, MC_DRAWS), rng.multivariate_normal(lnsig, C_lnsig, MC_DRAWS))
    xs = np.array([[level_x(X_GRID, fgr_curve(share, a, np.exp(b), rho), lv) for lv in LEVELS] for a, b in draws])
    return xs.std(axis=0) / xs.mean(axis=0)


