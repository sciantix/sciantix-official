# Functions to read and prepare data

def read_index(path=INDEX):
    """Factors of every run of mmm_inputs/index.txt: {run id: {column: value}}."""
    runs, names = {}, None
    with open(path) as fh:
        for line in fh:
            words = line.split()
            if line.startswith("#") and "run" in words:
                names = words[1:]
            elif names and words and not line.startswith("#") and len(words) == len(names):
                runs[words[0]] = {n: (float(w) if n not in ("run", "file") else w) for n, w in zip(names, words)}
    return runs


def read_pores(folder):
    """Columns of pores.csv of a run folder (header after the comment line), as arrays; cube names as strings."""
    path = os.path.join(folder, "pores.csv")
    if not os.path.exists(path):
        raise SystemExit(f"{path} not found: python3 break_order.py {folder} (mm-opera-hpc/polydispersebubble/scripts)")
    with open(path) as fh:
        lines = [line.rstrip("\n").split(",") for line in fh if line.strip() and not line.startswith("#")]
    names, rows = lines[0], lines[1:]
    cols = {n: [r[k] for r in rows] for k, n in enumerate(names)}
    out = {n: np.array(v, dtype=float) for n, v in cols.items() if n != "cube"}
    out["cube"] = np.array(cols["cube"])
    return out


def lognormal(s):
    """mu and sig of ln s (s > 0)."""
    ln = np.log(s[np.isfinite(s) & (s > 0.0)])
    return ln.mean(), ln.std(ddof=1)


def relative_pressure(p):
    """ln(p / p_ref) of every pore: 0 in a unit run (and with the pores.csv written before the pk runs)."""
    if "p_MPa" not in p or "p_ref_MPa" not in p:
        return np.zeros(len(p["s_hat"]))
    return np.log(p["p_MPa"] / p["p_ref_MPa"])


def load_of(p):
    """"pk" if the pores of the run have different pressures, "unit" otherwise."""
    return "pk" if np.ptp(relative_pressure(p)) > 1e-9 else "unit"

#%%
# Stats for dimensional class

def class_fits(p, cubes=None):
    """Per class: R, volume share, pores, mu, sig (log-normal of s_hat), from the pores of the given cubes (all if None).
    A cube drawn twice counts twice."""
    if cubes is None:
        cubes = np.unique(p["cube"])
    pick = np.concatenate([np.nonzero(p["cube"] == c)[0] for c in cubes])
    R, s, k = p["R_um"][pick], p["s_hat"][pick], p["class"][pick].astype(int)
    rho = relative_pressure(p)[pick]
    V = R**3
    out = []
    for j in np.unique(p["class"].astype(int)):
        m = k == j
        mu, sig = lognormal(s[m])
        out.append({"R": R[m][0], "share": V[m].sum() / V.sum(), "pores": int(m.sum()), "mu": mu, "sig": sig,
                    "s": s[m], "rho": float(rho[m].mean())})
    return out

#%%
# FGR

def fgr_model(fits, x):
    """FGR at x = p_ref / sigma_R (P_h = 0, no surface tension) from the log-normal classes: a pore of class k breaks
    when s_hat p_k > sigma_R, i.e. ln s_hat > -ln x - ln(p_k / p_ref) (p_k = p_ref in a unit run)."""
    return sum(f["share"] * ndtr((np.log(x) + f.get("rho", 0.0) + f["mu"]) / f["sig"]) for f in fits)


def fgr_cubes(p, x):
    """FGR of every cube at x, from its pores: rows = cubes."""
    out = []
    for c in np.unique(p["cube"]):
        m = (p["cube"] == c) & np.isfinite(p["x_c"])
        V = p["R_um"][m] ** 3
        out.append((p["x_c"][m][None, :] < x[:, None]) @ V / V.sum())
    return np.array(out)


def level_x(x, fgr, level):
    """x at which the increasing curve fgr reaches level (linear)."""
    return float(np.interp(level, fgr, x))


def bootstrap(p, x, sizes):
    """Error (2 standard deviations) of mu_k, sig_k and of x at the LEVELS, for a run of m cubes drawn from those of p."""
    rng = np.random.default_rng(BOOT_SEED)
    names = np.unique(p["cube"])
    out = {}
    for m in sizes:
        mus, sigs, xs = [], [], []
        for _ in range(BOOT):
            fits = class_fits(p, rng.choice(names, size=m, replace=True))
            mus.append([f["mu"] for f in fits])
            sigs.append([f["sig"] for f in fits])
            fgr = fgr_model(fits, x)
            xs.append([level_x(x, fgr, lv) for lv in LEVELS])
        out[m] = {"mu": 2 * np.std(mus, axis=0), "sig": 2 * np.std(sigs, axis=0),
                  "x": 2 * np.std(xs, axis=0) / np.mean(xs, axis=0)}
    return out

